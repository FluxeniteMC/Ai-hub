#!/usr/bin/env python3
"""Compose the catalog pull-request body.

Run from the repository root:

    python scripts/catalog-pr-body.py > body.md

Reads the catalogs as they are currently checked out (the catalog branch after
the push step) and prints a Markdown summary: what changed, which providers
refreshed, what validation ran, and what the data cannot tell you.

Kept as a standalone script rather than an inline heredoc so it can be unit
tested and so the workflow shell stays simple.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

SOURCES = (
    ("data/readme-models.json", "README"),
    ("data/openrouter.json", "OpenRouter"),
    ("data/groq.json", "Groq"),
    ("data/models.json", "Unified"),
)


def git(*args: str) -> str:
    # Explicit UTF-8: the default locale encoding on Windows cannot decode the
    # emoji and accented characters that appear in these diffs.
    result = subprocess.run(["git", *args], capture_output=True, encoding="utf-8", errors="replace")
    return result.stdout.strip() if result.returncode == 0 else ""


def load(path: str):
    try:
        return json.loads(Path(path).read_text(encoding="utf-8"))
    except Exception:
        return None


def diffstat(base: str) -> str:
    output = git("diff", "--stat", f"{base}...HEAD", "--", "data/")
    return output if output else "_No file-level changes._"


def provider_table() -> str:
    rows = [
        "| Source | Status | Models | Observed at | Note |",
        "|---|---|---|---|---|",
    ]
    for path, label in SOURCES:
        payload = load(path)
        if not payload:
            rows.append(f"| {label} | not present | — | — | — |")
            continue
        source = payload.get("source", {})
        note = (source.get("note") or "").replace("|", "\\|")
        if len(note) > 80:
            note = note[:77] + "…"
        rows.append(
            f"| {label} | {source.get('status', '?')} | {payload.get('count', '?')} "
            f"| {source.get('observed_at') or '—'} | {note or '—'} |"
        )
    return "\n".join(rows)


def model_table(base: str, limit: int = 40) -> str:
    head = load("data/models.json")
    if not head:
        return "_Unified catalog unavailable._"

    ids = [m["id"] for m in head.get("models", [])]
    try:
        before = json.loads(
            subprocess.run(
                ["git", "show", f"origin/{base}:data/models.json"],
                capture_output=True,
                encoding="utf-8",
                errors="replace",
                check=True,
            ).stdout
        )
        previous = {m["id"] for m in before.get("models", [])}
    except Exception:
        previous = set()

    current = set(ids)
    added = sorted(current - previous)
    removed = sorted(previous - current)

    lines = []
    if added:
        lines.append(f"**{len(added)} added**")
        lines.append("")
        for name in added[:limit]:
            lines.append(f"- `{name}`")
        if len(added) > limit:
            lines.append(f"- …and {len(added) - limit} more")
        lines.append("")
    if removed:
        lines.append(f"**{len(removed)} removed**")
        lines.append("")
        for name in removed[:limit]:
            lines.append(f"- `{name}`")
        lines.append("")

    if not added and not removed:
        lines.append("_Model membership is unchanged; only pricing or metadata moved._")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def review_queue_table(limit: int = 20) -> str:
    payload = load("data/models.json")
    queue = payload.get("review_queue") or []
    if not queue:
        return "_None — every entry matched a provider model by identity._"

    lines = [
        f"{len(queue)} README entr{'y' if len(queue) == 1 else 'ies'} could not be matched to a "
        "provider model by identity and are kept separate for human review.",
        "",
        "<details><summary>Review queue</summary>",
        "",
        "| README entry | Possible provider match |",
        "|---|---|",
    ]
    for item in queue[:limit]:
        names = ", ".join(c["name"] for c in item.get("candidates", [])) or "—"
        lines.append(f"| {item['name']} | {names} |")
    lines += ["", "</details>"]
    return "\n".join(lines)


def build(base: str) -> str:
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    return "\n".join(
        [
            "## 🤖 Automated catalog refresh",
            "",
            f"Generated by `catalog-update.yml` at {stamp}. "
            "**Not merged automatically** — a human must review and merge this.",
            "",
            "### What changed",
            "",
            "```",
            diffstat(base),
            "```",
            "",
            model_table(base),
            "### Provider refresh results",
            "",
            provider_table(),
            "",
            "### Validation",
            "",
            "- ✅ `convert.py` completed",
            "- ✅ Every generated file parses as JSON",
            "- ✅ Changes are confined to `data/`",
            "- ✅ Python tests (`unittest`) passed",
            "- ✅ JavaScript tests (`node --test`) passed",
            "- ✅ Frontend production build succeeded",
            "",
            "### Unverified matches",
            "",
            review_queue_table(),
            "",
            "### Limitations",
            "",
            "- A price is recorded only where a source states **both** an input and an output rate. "
            "A single figure is kept as text and never split into two rates.",
            "- A missing price is `null`, never `0`. Zero would assert a real, stated price of zero. "
            "Groq publishes no pricing on `/models`, so its entries are always `null`.",
            "- Distinct versions, quantisations, fine-tunes and variants are **never** merged, even "
            "when their names are similar. OpenRouter's date-pinned snapshots appear separately "
            "because they are distinct deployments.",
            "- README entries that cannot be matched by verified identity stay separate and are listed "
            "in the review queue above.",
            "- Repository content, provider descriptions and commit messages are treated as untrusted "
            "data and are never used as instructions.",
            "",
            "### How to review",
            "",
            "```bash",
            f"git fetch origin automation/catalog-update",
            f"git diff {base}...origin/automation/catalog-update -- data/",
            "```",
            "",
        ]
    )


def main(argv: list[str] | None = None) -> int:
    # The body contains emoji and non-ASCII model names. Windows consoles
    # default to cp1252 and would raise rather than print them.
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, ValueError):
            pass

    parser = argparse.ArgumentParser(description="Compose the catalog pull-request body")
    parser.add_argument("--base", default="main", help="base branch to diff against")
    args = parser.parse_args(argv)

    sys.stdout.write(build(args.base))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())